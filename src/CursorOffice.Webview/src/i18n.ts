let currentLanguage: OfficeLanguage = 'en';

export function setLanguage(language: OfficeLanguage): void {
  currentLanguage = language;
  document.documentElement.lang = language;
}

export function getLanguage(): OfficeLanguage {
  return currentLanguage;
}

export function localeTag(): string {
  return currentLanguage === 'cs' ? 'cs-CZ' : 'en-US';
}

export function t(key: TranslationKey, variables?: Record<string, string | number>): string {
  let value: string = (currentLanguage === 'cs' ? cs : en)[key];
  for (const [name, replacement] of Object.entries(variables ?? {})) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function statusLabel(status: AgentStatus): string {
  const keys: Record<AgentStatus, TranslationKey> = {
    unknown: 'statusUnknownLong',
    idle: 'statusIdle',
    working: 'statusWorking',
    waitingForUser: 'statusWaitingLong',
    error: 'statusErrorLong',
    completed: 'statusCompleted',
    offline: 'statusOffline'
  };
  return t(keys[status]);
}
